package com.wundark.binaural_beats

import android.app.Notification
import android.app.NotificationChannel
import android.app.NotificationManager
import android.app.PendingIntent
import android.app.Service
import android.content.Context
import android.content.Intent
import android.content.pm.ServiceInfo
import android.graphics.Bitmap
import android.os.Build
import android.os.Handler
import android.os.IBinder
import android.os.Looper
import android.os.PowerManager
import android.support.v4.media.MediaMetadataCompat
import android.support.v4.media.session.MediaSessionCompat
import android.support.v4.media.session.PlaybackStateCompat
import androidx.core.app.NotificationCompat
import androidx.core.app.ServiceCompat
import androidx.core.content.ContextCompat
import androidx.core.graphics.drawable.toBitmap
import org.json.JSONObject
import androidx.media.app.NotificationCompat as MediaNotificationCompat

/**
 * Keeps a session playing with the screen off and shows it as a media
 * player: a media notification (and lock screen and quick settings controls)
 * with play/pause, previous, next and a seek bar, which headset buttons
 * control too.
 *
 * Audio is generated by the Go engine in this process; without a foreground
 * service Android may throttle or kill the process once the app is in the
 * background. The service reads the engine's state directly (see Engine.kt),
 * since the page's timers may be suspended in the background, and its
 * controls call the engine directly for the same reason.
 *
 * While playing it holds a partial wake lock and checks the engine every
 * second; once playback stops it removes the notification and stops itself.
 */
class PlaybackService : Service() {
    companion object {
        private const val CHANNEL_ID = "playback"
        private const val NOTIFICATION_ID = 1
        private const val POLL_MS = 1_000L
        // Renewed on each poll, so it only expires if polling stops.
        private const val WAKE_LOCK_MS = 60_000L
        private const val SEEK_STEP_MS = 10_000L

        private const val ACTION_TOGGLE = "com.wundark.binaural_beats.TOGGLE"
        private const val ACTION_NEXT = "com.wundark.binaural_beats.NEXT"
        private const val ACTION_PREVIOUS = "com.wundark.binaural_beats.PREVIOUS"
        private const val ACTION_STOP = "com.wundark.binaural_beats.STOP"

        @Volatile
        private var running = false

        /** Shows the engine's state, starting the service if needed. */
        fun update(context: Context) {
            val intent = Intent(context, PlaybackService::class.java)
            try {
                if (running) {
                    // A running foreground service may be updated from the background.
                    context.startService(intent)
                } else {
                    ContextCompat.startForegroundService(context, intent)
                }
            } catch (e: Exception) {
                Logger.error("PlaybackService: could not start: $e")
            }
        }

        fun stop(context: Context) {
            context.stopService(Intent(context, PlaybackService::class.java))
        }
    }

    private val handler = Handler(Looper.getMainLooper())
    private val poll = Runnable { refresh(force = false) }
    private var wakeLock: PowerManager.WakeLock? = null
    private lateinit var session: MediaSessionCompat
    private var artwork: Bitmap? = null
    private var shownTitle: String? = null
    private var shownDurationMs = -1L
    private var shownNotification: String? = null

    private val callback = object : MediaSessionCompat.Callback() {
        override fun onPlay() = control { s ->
            if (s.paused) Engine.call("resume") else if (!s.playing) Engine.call("play")
        }

        override fun onPause() = control { s ->
            if (s.playing && !s.paused) Engine.call("pause")
        }

        override fun onStop() = control { Engine.call("stop") }
        override fun onSkipToNext() = control { Engine.call("next") }
        override fun onSkipToPrevious() = control { Engine.call("previous") }
        override fun onFastForward() = control { s -> seek(s.timeMs + SEEK_STEP_MS) }
        override fun onRewind() = control { s -> seek(s.timeMs - SEEK_STEP_MS) }
        override fun onSeekTo(pos: Long) = control { seek(pos) }
    }

    private fun seek(ms: Long) {
        Engine.call("seek", JSONObject().put("time", ms.coerceAtLeast(0) / 1000.0))
    }

    /** Runs [action] with the engine's state, then shows the result. */
    private fun control(action: (Engine.Status) -> Unit) {
        Engine.status()?.let(action)
        refresh()
    }

    override fun onCreate() {
        super.onCreate()
        session = MediaSessionCompat(this, "BinauralBeats").apply {
            setCallback(callback)
            setSessionActivity(openApp())
            isActive = true
        }
        artwork = try {
            ContextCompat.getDrawable(this, R.mipmap.ic_launcher)?.toBitmap(256, 256)
        } catch (e: Exception) {
            null
        }
    }

    override fun onBind(intent: Intent?): IBinder? = null

    override fun onStartCommand(intent: Intent?, flags: Int, startId: Int): Int {
        when (intent?.action) {
            ACTION_TOGGLE -> control { s ->
                if (s.paused) Engine.call("resume") else if (s.playing) Engine.call("pause")
            }
            ACTION_NEXT -> callback.onSkipToNext()
            ACTION_PREVIOUS -> callback.onSkipToPrevious()
            ACTION_STOP -> callback.onStop()
            else -> refresh()
        }
        // If the process is killed, the engine's session is gone too.
        return START_NOT_STICKY
    }

    override fun onDestroy() {
        handler.removeCallbacks(poll)
        releaseWakeLock()
        session.isActive = false
        session.release()
        running = false
        super.onDestroy()
    }

    /**
     * Shows the engine's state; stops once playback has stopped. The
     * notification is posted again only when it changes, unless [force]d.
     */
    private fun refresh(force: Boolean = true) {
        handler.removeCallbacks(poll)
        val status = Engine.status()
        val playing = status != null && status.playing && !status.paused

        if (status != null) showSession(status)
        val key = status?.let { "${title(it)}|${subtitle(it)}|${it.paused}|${hasNext(it)}" }
        // A service started with startForegroundService must call
        // startForeground, even when playback has already stopped.
        if (force || key != shownNotification) {
            shownNotification = key
            val type = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
                ServiceInfo.FOREGROUND_SERVICE_TYPE_MEDIA_PLAYBACK
            } else {
                0
            }
            ServiceCompat.startForeground(this, NOTIFICATION_ID, notification(status), type)
            running = true
        }

        if (status == null || !status.playing) {
            stopSelf()
            return
        }
        if (playing) {
            acquireWakeLock()
            handler.postDelayed(poll, POLL_MS)
        } else {
            releaseWakeLock()
        }
    }

    private fun title(status: Engine.Status?) =
        status?.name?.takeIf { it.isNotEmpty() } ?: getString(R.string.app_name)

    private fun subtitle(status: Engine.Status): String =
        if (status.playlistIndex >= 0) {
            getString(R.string.playback_playlist, status.playlistIndex + 1, status.playlistLength)
        } else {
            getString(R.string.app_name)
        }

    private fun hasNext(status: Engine.Status) =
        status.playlistIndex >= 0 && status.playlistLength > 1

    private fun showSession(status: Engine.Status) {
        val title = title(status)
        if (title != shownTitle || status.durationMs != shownDurationMs) {
            shownTitle = title
            shownDurationMs = status.durationMs
            session.setMetadata(
                MediaMetadataCompat.Builder()
                    .putString(MediaMetadataCompat.METADATA_KEY_TITLE, title)
                    .putString(MediaMetadataCompat.METADATA_KEY_ARTIST, subtitle(status))
                    .putLong(MediaMetadataCompat.METADATA_KEY_DURATION, status.durationMs)
                    .also { b -> artwork?.let { b.putBitmap(MediaMetadataCompat.METADATA_KEY_ART, it) } }
                    .build()
            )
        }

        val state = when {
            !status.playing -> PlaybackStateCompat.STATE_STOPPED
            status.paused -> PlaybackStateCompat.STATE_PAUSED
            else -> PlaybackStateCompat.STATE_PLAYING
        }
        var actions = PlaybackStateCompat.ACTION_PLAY or PlaybackStateCompat.ACTION_PAUSE or
            PlaybackStateCompat.ACTION_PLAY_PAUSE or PlaybackStateCompat.ACTION_STOP or
            PlaybackStateCompat.ACTION_SEEK_TO or PlaybackStateCompat.ACTION_FAST_FORWARD or
            PlaybackStateCompat.ACTION_REWIND or PlaybackStateCompat.ACTION_SKIP_TO_PREVIOUS
        if (hasNext(status)) actions = actions or PlaybackStateCompat.ACTION_SKIP_TO_NEXT
        session.setPlaybackState(
            PlaybackStateCompat.Builder()
                .setActions(actions)
                .setState(state, status.timeMs, if (state == PlaybackStateCompat.STATE_PLAYING) 1f else 0f)
                .build()
        )
    }

    private fun acquireWakeLock() {
        val lock = wakeLock ?: (getSystemService(Context.POWER_SERVICE) as PowerManager)
            .newWakeLock(PowerManager.PARTIAL_WAKE_LOCK, "BinauralBeats:playback")
            .also {
                it.setReferenceCounted(false)
                wakeLock = it
            }
        lock.acquire(WAKE_LOCK_MS)
    }

    private fun releaseWakeLock() {
        wakeLock?.let { if (it.isHeld) it.release() }
    }

    private fun openApp(): PendingIntent = PendingIntent.getActivity(
        this, 0,
        Intent(this, MainActivity::class.java).addFlags(Intent.FLAG_ACTIVITY_SINGLE_TOP),
        PendingIntent.FLAG_IMMUTABLE or PendingIntent.FLAG_UPDATE_CURRENT
    )

    private fun action(icon: Int, label: Int, action: String) = NotificationCompat.Action(
        icon, getString(label),
        PendingIntent.getService(
            this, action.hashCode(),
            Intent(this, PlaybackService::class.java).setAction(action),
            PendingIntent.FLAG_IMMUTABLE or PendingIntent.FLAG_UPDATE_CURRENT
        )
    )

    private fun notification(status: Engine.Status?): Notification {
        val manager = getSystemService(Context.NOTIFICATION_SERVICE) as NotificationManager
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
            manager.createNotificationChannel(
                NotificationChannel(CHANNEL_ID, getString(R.string.playback_channel), NotificationManager.IMPORTANCE_LOW)
                    .apply { setShowBadge(false) }
            )
        }
        val paused = status?.paused ?: false
        val builder = NotificationCompat.Builder(this, CHANNEL_ID)
            .setSmallIcon(R.drawable.ic_notification)
            .setLargeIcon(artwork)
            .setContentTitle(title(status))
            .setContentText(status?.let(::subtitle))
            .setContentIntent(openApp())
            .setDeleteIntent(
                PendingIntent.getService(
                    this, ACTION_STOP.hashCode(),
                    Intent(this, PlaybackService::class.java).setAction(ACTION_STOP),
                    PendingIntent.FLAG_IMMUTABLE or PendingIntent.FLAG_UPDATE_CURRENT
                )
            )
            .setOngoing(true)
            .setSilent(true)
            .setCategory(NotificationCompat.CATEGORY_TRANSPORT)
            .setVisibility(NotificationCompat.VISIBILITY_PUBLIC)
            .setForegroundServiceBehavior(NotificationCompat.FOREGROUND_SERVICE_IMMEDIATE)
            .addAction(action(R.drawable.ic_skip_previous, R.string.playback_previous, ACTION_PREVIOUS))
            .addAction(
                if (paused) action(R.drawable.ic_play, R.string.playback_play, ACTION_TOGGLE)
                else action(R.drawable.ic_pause, R.string.playback_pause, ACTION_TOGGLE)
            )
        val compact = if (status != null && hasNext(status)) {
            builder.addAction(action(R.drawable.ic_skip_next, R.string.playback_next, ACTION_NEXT))
            intArrayOf(0, 1, 2)
        } else {
            intArrayOf(0, 1)
        }
        return builder
            .setStyle(
                MediaNotificationCompat.MediaStyle()
                    .setMediaSession(session.sessionToken)
                    .setShowActionsInCompactView(*compact)
            )
            .build()
    }
}
