package com.wundark.binaural_beats

import android.app.Notification
import android.app.NotificationChannel
import android.app.NotificationManager
import android.app.PendingIntent
import android.app.Service
import android.content.Context
import android.content.Intent
import android.content.pm.ServiceInfo
import android.os.Build
import android.os.Handler
import android.os.IBinder
import android.os.Looper
import android.os.PowerManager
import androidx.core.app.NotificationCompat
import androidx.core.app.ServiceCompat
import androidx.core.content.ContextCompat

/**
 * Keeps a session playing with the screen off. Audio is generated by the Go
 * engine in this process; without a foreground service Android may throttle or
 * kill the process once the app is in the background.
 *
 * While playing it holds a partial wake lock so audio generation keeps
 * running; while paused it only keeps the notification. It stops itself when
 * the session is due to end, in case the web page's timers are suspended in the
 * background and never report the end.
 */
class PlaybackService : Service() {
    companion object {
        private const val CHANNEL_ID = "playback"
        private const val NOTIFICATION_ID = 1
        private const val EXTRA_TITLE = "title"
        private const val EXTRA_PLAYING = "playing"
        private const val EXTRA_REMAINING_MS = "remaining_ms"
        private const val END_MARGIN_MS = 30_000L

        @Volatile
        private var running = false

        /** Shows the notification and keeps playback alive, or updates it. */
        fun update(context: Context, title: String, playing: Boolean, remainingMs: Long) {
            val intent = Intent(context, PlaybackService::class.java)
                .putExtra(EXTRA_TITLE, title)
                .putExtra(EXTRA_PLAYING, playing)
                .putExtra(EXTRA_REMAINING_MS, remainingMs)
            try {
                if (running) {
                    // A running foreground service may be updated from the background.
                    context.startService(intent)
                } else {
                    ContextCompat.startForegroundService(context, intent)
                }
            } catch (e: Exception) {
                Logger.error("PlaybackService: could not start: $e")
            }
        }

        fun stop(context: Context) {
            context.stopService(Intent(context, PlaybackService::class.java))
        }
    }

    private val handler = Handler(Looper.getMainLooper())
    private val stopAtEnd = Runnable { stopSelf() }
    private var wakeLock: PowerManager.WakeLock? = null

    override fun onBind(intent: Intent?): IBinder? = null

    override fun onStartCommand(intent: Intent?, flags: Int, startId: Int): Int {
        val title = intent?.getStringExtra(EXTRA_TITLE) ?: getString(R.string.app_name)
        val playing = intent?.getBooleanExtra(EXTRA_PLAYING, true) ?: true
        val remainingMs = intent?.getLongExtra(EXTRA_REMAINING_MS, 0L) ?: 0L

        val type = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
            ServiceInfo.FOREGROUND_SERVICE_TYPE_MEDIA_PLAYBACK
        } else {
            0
        }
        ServiceCompat.startForeground(this, NOTIFICATION_ID, notification(title, playing), type)
        running = true

        handler.removeCallbacks(stopAtEnd)
        if (playing) {
            acquireWakeLock(remainingMs + END_MARGIN_MS)
            handler.postDelayed(stopAtEnd, remainingMs + END_MARGIN_MS)
        } else {
            releaseWakeLock()
        }
        // If the process is killed, the engine's session is gone too.
        return START_NOT_STICKY
    }

    override fun onDestroy() {
        handler.removeCallbacks(stopAtEnd)
        releaseWakeLock()
        running = false
        super.onDestroy()
    }

    private fun acquireWakeLock(timeoutMs: Long) {
        val lock = wakeLock ?: (getSystemService(Context.POWER_SERVICE) as PowerManager)
            .newWakeLock(PowerManager.PARTIAL_WAKE_LOCK, "BinauralBeats:playback")
            .also {
                it.setReferenceCounted(false)
                wakeLock = it
            }
        lock.acquire(timeoutMs)
    }

    private fun releaseWakeLock() {
        wakeLock?.let { if (it.isHeld) it.release() }
    }

    private fun notification(title: String, playing: Boolean): Notification {
        val manager = getSystemService(Context.NOTIFICATION_SERVICE) as NotificationManager
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
            manager.createNotificationChannel(
                NotificationChannel(CHANNEL_ID, getString(R.string.playback_channel), NotificationManager.IMPORTANCE_LOW)
                    .apply { setShowBadge(false) }
            )
        }
        val open = PendingIntent.getActivity(
            this, 0,
            Intent(this, MainActivity::class.java).addFlags(Intent.FLAG_ACTIVITY_SINGLE_TOP),
            PendingIntent.FLAG_IMMUTABLE or PendingIntent.FLAG_UPDATE_CURRENT
        )
        return NotificationCompat.Builder(this, CHANNEL_ID)
            .setSmallIcon(R.drawable.ic_notification)
            .setContentTitle(title)
            .setContentText(getString(if (playing) R.string.playback_playing else R.string.playback_paused))
            .setContentIntent(open)
            .setOngoing(true)
            .setSilent(true)
            .setCategory(NotificationCompat.CATEGORY_TRANSPORT)
            .setVisibility(NotificationCompat.VISIBILITY_PUBLIC)
            .setForegroundServiceBehavior(NotificationCompat.FOREGROUND_SERVICE_IMMEDIATE)
            .build()
    }
}
